'use strict';
const { test } = require('node:test');
const assert = require('node:assert/strict');
const M = require('../lib/etaModel');
const eta = require('../lib/eta');

const BETA = M.PARAMS.beta.slice();
const near = (a, b, tol, msg) => assert.ok(Math.abs(a - b) <= tol, (msg || '') + ' ' + a + ' vs ' + b);

test('phi: known values of the standard normal CDF, accurate in both tails', () => {
  near(M.phi(0), 0.5, 1e-15);
  near(M.phi(1), 0.8413447460685429, 1e-14);
  near(M.phi(-1), 0.15865525393145707, 1e-14);
  near(M.phi(1.959963984540054), 0.975, 1e-9);
  near(M.phi(-3) / 0.0013498980316301, 1, 1e-9);
  near(M.phi(-6) / 9.865876450377e-10, 1, 1e-8);
  assert.equal(M.phi(-40), 0); assert.equal(M.phi(40), 1);
  near(M.surv(5) / 2.866515718791946e-7, 1, 1e-8);
});

test('phiInv inverts phi and handles the edges', () => {
  for (const p of [1e-12, 1e-9, 1e-4, 0.01, 0.1, 0.3, 0.5, 0.7, 0.9, 0.99, 1 - 1e-6]) near(M.phi(M.phiInv(p)) / p, 1, 1e-8, 'p=' + p);
  near(M.phiInv(0.975), 1.959963984540054, 1e-12);
  near(M.phiInv(0.5), 0, 1e-15);
  assert.equal(M.phiInv(0), -Infinity); assert.equal(M.phiInv(1), Infinity); assert.ok(Number.isNaN(M.phiInv(NaN)) || M.phiInv(NaN) === -Infinity);
});

test('rng is deterministic and uniform enough', () => {
  const a = M.rng(7), b = M.rng(7);
  const xs = Array.from({ length: 2000 }, () => a());
  assert.deepEqual(xs.slice(0, 5), Array.from({ length: 5 }, () => b()));
  assert.ok(xs.every((x) => x >= 0 && x < 1));
  near(xs.reduce((s, v) => s + v, 0) / xs.length, 0.5, 0.03);
});

test('fitBeta: the prior without enough rows, follows the data with plenty, and never returns garbage', () => {
  assert.deepEqual(M.fitBeta([], M.PARAMS), BETA);
  assert.deepEqual(M.fitBeta(null, M.PARAMS), BETA);
  // data generated by ln D = 5 - 1 * ln(np) + 0 * pos -> the fit moves from the prior toward it
  const rows = [];
  for (let i = 0; i < 400; i++) { const np = 1 + (i % 12); rows.push({ ln: 5 - Math.log(np), np, pos: (i % 5) / 4 }); }
  const b = M.fitBeta(rows, M.PARAMS);
  near(b[0], 5, 0.5); near(b[1], -1, 0.15); near(b[2], 0, 0.35);   // ridge toward the prior keeps a rest of it, by design
  const few = M.fitBeta(rows.slice(0, 12), M.PARAMS);
  assert.ok(few[0] > b[0] && few[0] < BETA[0], 'few rows: the intercept sits between the data (5) and the prior (' + BETA[0] + '): ' + few[0]);
  assert.deepEqual(M.fitBeta(Array.from({ length: 30 }, () => ({ ln: NaN, np: 1, pos: 0 })), M.PARAMS), BETA);
});

test('predictAgent: quantiles are ordered and positive; deep in the tail the remaining time grows with the elapsed time', () => {
  const med = {};
  for (const e of [20, 60, 180, 600, 1800, 5400, 20000]) {
    const p = M.predictAgent({ size: 1, pos: 0.5, elapsedSec: e, doneSec: [], runningSec: [], others: [] }, BETA, null);
    const q = [0.1, 0.2, 0.5, 0.85, 0.95].map((x) => p.quantile(x));
    for (let i = 1; i < q.length; i++) assert.ok(q[i] >= q[i - 1], 'ordered at e=' + e);
    assert.ok(q[0] > 0);
    med[e] = q[2];
    assert.ok(p.survive > 0 && p.survive <= 1);
  }
  assert.ok(med[1800] < med[5400] && med[5400] < med[20000], 'a long-running agent is expected to need longer still');
  assert.ok(med[20] > 300 && med[20] < 3600, 'a fresh single agent: minutes, not seconds or hours');
});

test('predictAgent: finished siblings that were quick pull the estimate down, slow ones push it up (same elapsed time)', () => {
  const base = { size: 8, pos: 0.5, elapsedSec: 100, runningSec: [100, 100], others: [] };
  const none = M.predictAgent(Object.assign({ doneSec: [] }, base), BETA, null).quantile(0.5);
  const quick = M.predictAgent(Object.assign({ doneSec: [50, 60, 70, 80] }, base), BETA, null).quantile(0.5);
  const slow = M.predictAgent(Object.assign({ doneSec: [900, 1000, 1100, 1200] }, base), BETA, null).quantile(0.5);
  assert.ok(quick < none && none < slow, quick + ' < ' + none + ' < ' + slow);
  assert.ok(slow > 5 * quick, 'siblings carry a lot of information');
});

test('predictAgent: finished agents of earlier phases of the same run tell how slow the run is', () => {
  const base = { size: 1, pos: 1, elapsedSec: 60, doneSec: [], runningSec: [] };
  const fastRun = M.predictAgent(Object.assign({ others: [{ size: 1, pos: 0, doneSec: [60] }, { size: 2, pos: 0.5, doneSec: [50, 70] }] }, base), BETA, null).quantile(0.5);
  const slowRun = M.predictAgent(Object.assign({ others: [{ size: 1, pos: 0, doneSec: [3600] }, { size: 2, pos: 0.5, doneSec: [3000, 3300] }] }, base), BETA, null).quantile(0.5);
  assert.ok(slowRun > 3 * fastRun, fastRun + ' vs ' + slowRun);
});

test('predictAgent: a phase with many agents is expected to be quicker than a single big one', () => {
  const one = M.predictAgent({ size: 1, pos: 0.5, elapsedSec: 30, doneSec: [], runningSec: [], others: [] }, BETA, null).quantile(0.5);
  const many = M.predictAgent({ size: 20, pos: 0.5, elapsedSec: 30, doneSec: [], runningSec: [], others: [] }, BETA, null).quantile(0.5);
  assert.ok(many < one / 2, many + ' vs ' + one);
});

test('predictAgent: the quantile function is strictly increasing from the first to the last percentile', () => {
  const p = M.predictAgent({ size: 3, pos: 0.2, elapsedSec: 200, doneSec: [150, 400], runningSec: [200], others: [] }, BETA, null);
  let prev = 0;
  for (let q = 0.01; q < 0.995; q += 0.02) { const v = p.quantile(q); assert.ok(Number.isFinite(v) && v > prev, 'q=' + q.toFixed(2) + ' ' + v + ' > ' + prev); prev = v; }
});

test('predictAgent survives extreme inputs without NaN: huge elapsed time, no evidence, all siblings still running', () => {
  for (const e of [1, 15, 86400, 1e7]) {
    const p = M.predictAgent({ size: 40, pos: 1, elapsedSec: e, doneSec: [], runningSec: Array(39).fill(e), others: [] }, BETA, null);
    for (const q of [0.2, 0.5, 0.85]) assert.ok(Number.isFinite(p.quantile(q)) && p.quantile(q) > 0, 'e=' + e);
    assert.ok(p.survive >= 0 && p.survive <= 1);
  }
});

test('predictWorkflow: deterministic, ordered, and phases that have not started add time', () => {
  const ctx = { size: 1, pos: 0, runningSec: [120], doneSec: [], others: [], ahead: 0 };
  const a = M.predictWorkflow(ctx, BETA, null), b = M.predictWorkflow(ctx, BETA, null);
  assert.equal(a.quantile(0.5), b.quantile(0.5));
  const c = M.predictWorkflow(Object.assign({}, ctx, { ahead: 2 }), BETA, null);
  assert.ok(c.quantile(0.5) > a.quantile(0.5) + 600, 'two more phases of about 10 minutes each');
  const q = [0.1, 0.5, 0.9].map((x) => c.quantile(x));
  assert.ok(q[0] < q[1] && q[1] < q[2]);
  const idle = M.predictWorkflow({ size: 1, pos: 0, runningSec: [], doneSec: [], others: [], ahead: 1 }, BETA, null);
  assert.ok(idle.quantile(0.5) > 60, 'nothing running but a phase ahead: its typical duration');
});

test('predictWorkflow: the slowest of many agents takes longer than a single one', () => {
  const one = M.predictWorkflow({ size: 1, pos: 0.5, runningSec: [100], doneSec: [], others: [], ahead: 0 }, BETA, null).quantile(0.5);
  const many = M.predictWorkflow({ size: 8, pos: 0.5, runningSec: Array(8).fill(100), doneSec: [], others: [], ahead: 0 }, BETA, null).quantile(0.5);
  const single8 = M.predictAgent({ size: 8, pos: 0.5, elapsedSec: 100, doneSec: [], runningSec: Array(7).fill(100), others: [] }, BETA, null).quantile(0.5);
  assert.ok(many > single8, 'max over agents >= one agent: ' + many + ' vs ' + single8);
  assert.ok(one > 0);
});

test('lognormalRemaining: median remaining time of a log-normal given survival', () => {
  // with elapsed -> 0 the median remaining is the median duration
  near(M.lognormalRemaining(Math.log(600), 0.5, 1, 0.5), 600, 5);
  // survival conditioning: after 10 minutes the median remaining time is shorter than the median duration but positive
  const r = M.lognormalRemaining(Math.log(600), 0.5, 600, 0.5);
  assert.ok(r > 0 && r < 600);
  assert.ok(M.lognormalRemaining(Math.log(600), 0.5, 600, 0.9) > r);
});

// ---------------------------------------------------------------------------------------------------------------------------
// Calibration on synthetic runs drawn from the model's own generative process: if the conditioning (siblings, censoring, survival)
// is implemented correctly, the 20-85 % span covers the truth about 65 % of the time (time-weighted) and misses on the high side
// about 15 % of the time. The real-data version of this check is tools/eta-eval.js.
// ---------------------------------------------------------------------------------------------------------------------------

test('calibration on synthetic runs: the shown span holds its promise (time-weighted)', () => {
  const P = M.PARAMS, rnd = M.rng(2024);
  const normal = () => M.phiInv(Math.min(1 - 1e-12, Math.max(1e-12, rnd())));
  let w = 0, inside = 0, above = 0, n = 0;
  for (let run = 0; run < 60; run++) {
    const np = [1, 2, 3, 5, 8, 12][Math.floor(rnd() * 6)], pos = [0, 0.5, 1][Math.floor(rnd() * 3)];
    const theta = Math.sqrt(P.tauR * P.tauR + P.tauP * P.tauP) * normal();
    const mu = BETA[0] + BETA[1] * Math.log(np) + BETA[2] * pos;
    const durs = Array.from({ length: np }, () => Math.exp(mu + theta + P.s * normal()));
    for (let i = 0; i < np; i++) {
      for (const f of [0.25, 0.5, 0.75]) {
        const e = durs[i] * f;
        if (e < 15) continue;
        const done = durs.filter((d, j) => j !== i && d <= e), runn = durs.filter((d, j) => j !== i && d > e).map(() => e);
        const est = eta.estimateAgent({ state: 'running', elapsedSec: e, kind: 'wf', label: 'x', phase: 'p', phaseSize: np, phasePos: pos, siblingsDoneSec: done, siblingsRunningSec: runn, otherPhases: [] }, null);
        if (!Number.isFinite(est.lo)) continue;
        const truth = durs[i] - e;
        w += durs[i]; n++;
        if (truth > est.hi) above += durs[i]; else if (truth >= est.lo) inside += durs[i];
      }
    }
  }
  assert.ok(n > 150, 'enough samples: ' + n);
  assert.ok(inside / w > 0.5 && inside / w < 0.85, 'inside ' + (inside / w).toFixed(2));
  assert.ok(above / w < 0.25, 'above ' + (above / w).toFixed(2));
});
